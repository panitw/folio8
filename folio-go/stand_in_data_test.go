// TestStandInGeneratorReadsNoClock is the other half of the determinism
// criterion, stated about the SOURCE: there is no clock in it. The
// positive control is a token the file genuinely contains, so a scan that
// silently read the wrong file cannot pass.
func TestStandInGeneratorReadsNoClock(t *testing.T) {
	// Comments are stripped first, for the reason design-contract.test.ts
	// strips them: the prose above the fixed instant explains what the
	// generator refuses to reach for, and a whole-file scan would be
	// satisfied by the explanation instead of by the code. The stripping
	// is a real Go parse, not a "//" search — see
	// TestStandInCommentStrippingIsAParseNotASearch for the two cases a
	// search gets wrong in OPPOSITE directions.
	source := standInSourceWithoutComments(t, "stand_in_data.go")
	if !strings.Contains(source, "func standInData(") {
		t.Fatal("positive control: the scanned file is not the generator, or the strip removed its declarations")
	}
	for _, forbidden := range []string{`"time"`, "time.Now", "math/rand", "os.Getenv", "rand.", "Unix()"} {
		if strings.Contains(source, forbidden) {
			t.Fatalf("the generator reaches for %q — the stand-in must be byte-deterministic on every run and every target", forbidden)
		}
	}
}

