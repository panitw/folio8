// standInShell wraps content-band element JSON in the smallest document
// that renders. Most fixtures only need the content band; the ones that
// exercise the band WALK use standInBandShell directly.
func standInShell(elements string) string { return standInBandShell("", elements, "") }

// standInBandShell populates all three bands. It exists because a shell
// that hardcoded empty pageHeader/pageFooter arrays made two thirds of
// the band walk unverifiable: reducing the walk to Bands.Content alone
// left the whole package green.
func standInBandShell(header, content, footer string) string {
	return fmt.Sprintf(`{
  "assets": {},
  "bands": {
    "content": {"elements": [%s]},
    "pageFooter": {"elements": [%s], "height": 20},
    "pageHeader": {"elements": [%s], "height": 20}
  },
  "fonts": {"body": ["Noto Sans"]},
  "locale": "en",
  "nextId": 20,
  "page": {"margin": {"bottom": 36, "left": 36, "right": 36, "top": 36}, "orientation": "portrait", "size": "A4"},
  "utcOffset": "+00:00",
  "version": "1.0"
}
`, content, footer, header)
}

// standInTextElement is one text element carrying value verbatim. The
// value is JSON-quoted here rather than by the caller so a pattern
// literal's own quotes survive.
func standInTextElement(id, value string) string {
	return fmt.Sprintf(`{"id": %q, "type": "text", "x": 0, "y": 0, "width": 460, "height": 20, "value": %q, "style": {"fontFamily": "body", "fontSize": 12}}`, id, value)
}

func standInTemplate(t *testing.T, elements string) *Template {
	t.Helper()
	tpl, err := ParseTemplate([]byte(standInShell(elements)))
	if err != nil {
		t.Fatalf("presence precondition: the fixture template does not parse: %v", err)
	}
	return tpl
}

func standInBytes(t *testing.T, tpl *Template) []byte {
	t.Helper()
	out, err := standInData(tpl)
	if err != nil {
		t.Fatalf("StandInData: %v", err)
	}
	return out
}

// TestStandInRulesCoverTheEngineFunctionRegistry is THE exhaustiveness
// gate, ported from internal/expr's
// TestImplementedEntriesMatchEvalCallSwitch: set equality in BOTH
// directions between the generator's per-function rules and the engine's
// own registry, with NO function name restated anywhere in this test.
//
// Adding a ninth function to internal/expr's closed table without a
// matching stand-in rule reds this, naming that function.
func TestStandInRulesCoverTheEngineFunctionRegistry(t *testing.T) {
	engineNames := map[string]bool{}
	for _, name := range expr.LegalFunctionNames() {
		engineNames[name] = true
	}
	ruleNames := map[string]bool{}
	for _, name := range slices.Sorted(maps.Keys(standInFunctionRules)) {
		ruleNames[name] = true
	}

	for _, name := range slices.Sorted(maps.Keys(engineNames)) {
		if !ruleNames[name] {
			t.Errorf("%s: the engine's function registry declares this, but the stand-in generator has no value-kind rule for it", name)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(ruleNames)) {
		if !engineNames[name] {
			t.Errorf("%s: the stand-in generator has a rule for this, but the engine's function registry has no such function", name)
		}
	}
	// Presence precondition (D-000.9): an empty extraction on either
	// side would make both comparisons above pass vacuously.
	if len(engineNames) == 0 || len(ruleNames) == 0 {
		t.Fatalf("presence precondition: engine names %d, generator rules %d — a zero on either side passes vacuously", len(engineNames), len(ruleNames))
	}
}

// TestStandInDocumentIsAcceptedByEveryFunction is the round trip: for each
// legal function, a real template using it is generated for, rendered with
// the generated bytes, and required to SUCCEED. The engine is the judge of
// whether the stand-in is legal, not this test's opinion of it.
//
// The fixture set is itself checked against the engine's registry, so a
// ninth function reds here too rather than being silently unexercised.
func TestStandInDocumentIsAcceptedByEveryFunction(t *testing.T) {
	// Each entry is one text-element value that uses the named function
	// on a path the generator must supply. sum/count return numbers; a
	// bare number would print as its exact decimal, but both stay wrapped
	// in formatNumber so that function's operand path is exercised too.
	fixtures := map[string]string{
		"sum":          `Total {{formatNumber(sum(ledger.amount), "0.00")}}`,
		"count":        `Rows {{formatNumber(count(ledger), "0")}}`,
		"avg":          `Mean {{avg(ledger.amount)}}`,
		"upper":        `Loud {{upper(customer.name)}}`,
		"lower":        `Quiet {{lower(customer.name)}}`,
		"formatNumber": `Money {{formatNumber(invoice.total, "#,##0.00")}}`,
		"formatDate":   `Dated {{formatDate(invoice.issued, "yyyy-MM-dd")}}`,
		"if":           `Flagged {{if(flags.vip, "yes", "no")}}`,
	}
	if missing := slices.Sorted(maps.Keys(fixtures)); len(missing) == 0 {
		t.Fatal("presence precondition: no round-trip fixtures declared")
	}
	for _, name := range expr.LegalFunctionNames() {
		if _, ok := fixtures[name]; !ok {
			t.Fatalf("%s: the engine declares this function and no round-trip fixture exercises it", name)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(fixtures)) {
		t.Run(name, func(t *testing.T) {
			tpl := standInTemplate(t, standInTextElement("e1", fixtures[name]))
			data := standInBytes(t, tpl)
			if _, err := Render(tpl, Data(data), nil, testShippedFontSet()); err != nil {
				t.Fatalf("the stand-in document %s was refused by Render: %v", data, err)
			}
		})
	}
}

// TestStandInScalarBindingRendersAsNothing pins the story's second
// acceptance criterion against a LITERAL expected document, never against
// a value read back out of the generator (D-11.2.2, D-11.2.8).
func TestStandInScalarBindingRendersAsNothing(t *testing.T) {
	tpl, err := ParseTemplate(standInReadFile(t, "testdata/example/first-pdf.folio"))
	if err != nil {
		t.Fatalf("presence precondition: the shipped example does not parse: %v", err)
	}
	got := standInBytes(t, tpl)
	if string(got) != `{"customer":{"name":""}}` {
		t.Fatalf("stand-in document = %s, want {\"customer\":{\"name\":\"\"}}", got)
	}
	standIn, err := Render(tpl, Data(got), nil, testShippedFontSet())
	if err != nil {
		t.Fatalf("the stand-in render failed: %v", err)
	}
	// AND THE PAGE IS THE PAGE AN EMPTY VALUE PRODUCES. Rendering the
	// same template against a hand-written document whose one bound path
	// is the empty string must produce the same bytes — which is what
	// "renders as nothing at all" means, stated against a literal rather
	// than against the generator's own output.
	empty, err := Render(tpl, Data(`{"customer":{"name":""}}`), nil, testShippedFontSet())
	if err != nil {
		t.Fatalf("the literal empty-string render failed: %v", err)
	}
	if !bytes.Equal(standIn.Bytes, empty.Bytes) {
		t.Fatal("the stand-in render differs from the render of a literal empty string — the bound path did not render as nothing")
	}
}

// TestAbsentDataStillFailsWithTheLocatedBindingError is the story's
// central promise and gets its own pin: nothing here changes what Render
// does when data is genuinely ABSENT.
func TestAbsentDataStillFailsWithTheLocatedBindingError(t *testing.T) {
	tpl, err := ParseTemplate(standInReadFile(t, "testdata/example/first-pdf.folio"))
	if err != nil {
		t.Fatalf("presence precondition: the shipped example does not parse: %v", err)
	}
	_, rerr := Render(tpl, Data(`{}`), nil, testShippedFontSet())
	if rerr == nil {
		t.Fatal("Render succeeded with absent data — the located BINDING_PATH_ABSENT Error is this story's central invariant")
	}
	var renderErr *RenderError
	if !errors.As(rerr, &renderErr) {
		t.Fatalf("Render returned %T, not a *RenderError carrying a located Diagnostic: %v", rerr, rerr)
	}
	if renderErr.Diagnostic.Code != DiagCodeBindingPathAbsent {
		t.Fatalf("diagnostic code = %q, want %q", renderErr.Diagnostic.Code, DiagCodeBindingPathAbsent)
	}
	if renderErr.Diagnostic.ElementID == "" {
		t.Fatal("the Error lost its element location")
	}
	if !strings.Contains(renderErr.Diagnostic.Message, "customer.name") {
		t.Fatalf("the Error no longer names the absent path: %s", renderErr.Diagnostic.Message)
	}
}

// TestStandInCollectionIsEmptyAndRowScopeIsNeverEvaluated covers the
// bound-table row of the matrix. The stand-in collection is [], the table
// renders header-only, and the proof that no row exists is that the page
// is byte-identical to the page a hand-written empty collection produces.
func TestStandInCollectionIsEmptyAndRowScopeIsNeverEvaluated(t *testing.T) {
	table := `{"id": "e1", "type": "table", "x": 0, "y": 0, "bind": "transactions[]", "headerHeight": 12,
	  "style": {"fontFamily": "body", "fontSize": 9},
	  "columns": [
	    {"id": "e2", "label": "Date", "width": 120, "bind": "{{row.date}}"},
	    {"id": "e3", "label": "Amount", "width": 120, "bind": "{{formatNumber(row.amount, \"#,##0.00\")}}", "footer": "avg"}
	  ]}`
	tpl := standInTemplate(t, table)
	got := standInBytes(t, tpl)
	// THE RENDER IS ASSERTED BEFORE THE LITERAL, DELIBERATELY. [] is
	// load-bearing rather than incidental: with even one row in the
	// collection the row scope IS evaluated, and this template's column
	// bindings — for which no stand-in exists, and deliberately so — then
	// fail the render outright. Asserting the document text first would
	// red on the spelling and never reach the consequence that makes the
	// spelling matter.
	result, err := Render(tpl, Data(got), nil, testShippedFontSet())
	if err != nil {
		t.Fatalf("the stand-in table render failed: %v", err)
	}
	if string(got) != `{"transactions":[]}` {
		t.Fatalf("stand-in document = %s, want {\"transactions\":[]}", got)
	}
	explicit, err := Render(tpl, Data(`{"transactions":[]}`), nil, testShippedFontSet())
	if err != nil {
		t.Fatalf("the literal empty-collection render failed: %v", err)
	}
	if !bytes.Equal(result.Bytes, explicit.Bytes) {
		t.Fatal("the stand-in table render differs from a literal empty collection — the table did not render header-only")
	}
	// The engine's own empty-average Warning is SHOWN, not suppressed:
	// the avg footer over the empty stand-in collection is exactly the
	// case CodeEmptyAverage exists for.
	found := false
	for _, diagnostic := range result.Diagnostics {
		if diagnostic.Code == DiagCodeEmptyAverage {
			found = true
		}
	}
	if !found {
		t.Fatalf("the avg footer over the empty stand-in collection produced no %s Warning: %+v", DiagCodeEmptyAverage, result.Diagnostics)
	}
}

// TestStandInSharedContextsIntersect covers the two multi-context rows of
// the matrix: the pair that HAS a common value, and the pair that does
// not.
func TestStandInSharedContextsIntersect(t *testing.T) {
	t.Run("text and visibleIf share null", func(t *testing.T) {
		elements := standInTextElement("e1", "VIP: {{flags.vip}}") +
			`, {"id": "e2", "type": "rect", "x": 0, "y": 40, "width": 100, "height": 10, "visibleIf": "flags.vip"}`
		tpl := standInTemplate(t, elements)
		got := standInBytes(t, tpl)
		if string(got) != `{"flags":{"vip":null}}` {
			t.Fatalf("stand-in document = %s, want {\"flags\":{\"vip\":null}}", got)
		}
		result, err := Render(tpl, Data(got), nil, testShippedFontSet())
		if err != nil {
			t.Fatalf("the shared-null render failed: %v", err)
		}
		// D-3.2.3: a null condition hides the element SILENTLY — no
		// diagnostic at all.
		if len(result.Diagnostics) != 0 {
			t.Fatalf("a null visibility condition emitted diagnostics: %+v", result.Diagnostics)
		}
	})

	// A number in text prints as its exact decimal (2026-09-13), so text
	// and formatNumber now share the zero stand-in and preview renders.
	t.Run("text and formatNumber share zero", func(t *testing.T) {
		elements := standInTextElement("e1", `Raw {{invoice.total}} formatted {{formatNumber(invoice.total, "0.00")}}`)
		tpl := standInTemplate(t, elements)
		got := standInBytes(t, tpl)
		if string(got) != `{"invoice":{"total":0}}` {
			t.Fatalf("stand-in document = %s, want {\"invoice\":{\"total\":0}}", got)
		}
		if _, err := Render(tpl, Data(got), nil, testShippedFontSet()); err != nil {
			t.Fatalf("the shared-zero render failed: %v", err)
		}
	})

	t.Run("text and a direct divisor share one", func(t *testing.T) {
		elements := standInTextElement("e1", `{{d}} {{10 / d}}`)
		tpl := standInTemplate(t, elements)
		got := standInBytes(t, tpl)
		if string(got) != `{"d":1}` {
			t.Fatalf("stand-in document = %s, want {\"d\":1}", got)
		}
		if _, err := Render(tpl, Data(got), nil, testShippedFontSet()); err != nil {
			t.Fatalf("the shared-one render failed: %v", err)
		}
	})

	t.Run("text and visibleIf and formatNumber share nothing", func(t *testing.T) {
		elements := standInTextElement("e1", `Raw {{invoice.total}} formatted {{formatNumber(invoice.total, "0.00")}}`) +
			`, {"id": "e2", "type": "rect", "x": 0, "y": 40, "width": 100, "height": 10, "visibleIf": "invoice.total"}`
		tpl := standInTemplate(t, elements)
		_, err := standInData(tpl)
		if err == nil {
			t.Fatal("StandInData produced a document for a path whose contexts share no legal value — it must refuse, never mangle")
		}
		message := err.Error()
		for _, want := range []string{`"invoice.total"`, "a text binding", "formatNumber()'s operand", "a visibility condition"} {
			if !strings.Contains(message, want) {
				t.Fatalf("the refusal does not name %q: %s", want, message)
			}
		}
	})
}

