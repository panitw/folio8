// TestStandInRulesCoverEveryElementKind is the SECOND exhaustiveness
// gate. The element-kind set is AST-EXTRACTED from internal/template's
// own closedElementTypes literal — never restated here — so adding a
// sixth kind to the format reds this until the generator declares what
// that kind's data paths are.
func TestStandInRulesCoverEveryElementKind(t *testing.T) {
	formatKinds := closedElementTypesFromSource(t)
	ruleKinds := map[string]bool{}
	for _, kind := range slices.Sorted(maps.Keys(standInElementRules)) {
		ruleKinds[string(kind)] = true
	}
	for _, kind := range slices.Sorted(maps.Keys(formatKinds)) {
		if !ruleKinds[kind] {
			t.Errorf("%s: the format declares this element kind, but the stand-in generator has no rule for it", kind)
		}
	}
	for _, kind := range slices.Sorted(maps.Keys(ruleKinds)) {
		if !formatKinds[kind] {
			t.Errorf("%s: the stand-in generator has a rule for this, but the format declares no such element kind", kind)
		}
	}
	if len(formatKinds) == 0 || len(ruleKinds) == 0 {
		t.Fatalf("presence precondition: format kinds %d, generator rules %d — a zero on either side passes vacuously", len(formatKinds), len(ruleKinds))
	}
}

// closedElementTypesFromSource reads internal/template/closedsets.go and
// returns the keys of its closedElementTypes composite literal. It is an
// AST walk rather than a second literal for the same reason
// table_derivational_test.go's switch scan is: a restated set agrees
// with itself forever.
func closedElementTypesFromSource(t *testing.T) map[string]bool {
	t.Helper()
	const path = "internal/template/closedsets.go"
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
	kinds := map[string]bool{}
	ast.Inspect(file, func(node ast.Node) bool {
		spec, ok := node.(*ast.ValueSpec)
		if !ok || len(spec.Names) != 1 || spec.Names[0].Name != "closedElementTypes" || len(spec.Values) != 1 {
			return true
		}
		literal, ok := spec.Values[0].(*ast.CompositeLit)
		if !ok {
			return true
		}
		for _, element := range literal.Elts {
			pair, ok := element.(*ast.KeyValueExpr)
			if !ok {
				continue
			}
			key, ok := pair.Key.(*ast.BasicLit)
			if !ok || key.Kind != token.STRING {
				continue
			}
			unquoted, uerr := strconv.Unquote(key.Value)
			if uerr != nil {
				t.Fatalf("unquote %s: %v", key.Value, uerr)
			}
			kinds[unquoted] = true
		}
		return false
	})
	return kinds
}

// TestStandInSetHasOneBitPerValue ties standInSetBits to the TYPE rather
// than to its own declaration. The compile-time constant in the
// generator ties the MEMBER COUNT to standInSetBits; without this, both
// could be edited to agree with each other while the type stayed narrow.
func TestStandInSetHasOneBitPerValue(t *testing.T) {
	// The shifts are through VARIABLES so they are evaluated at run time
	// against the real type width; as constant expressions the compiler
	// would reject the overflow instead of demonstrating it.
	one, top, past := standInSet(1), uint(standInSetBits-1), uint(standInSetBits)
	if one<<top == 0 {
		t.Fatalf("standInSet is narrower than standInSetBits (%d): its top bit truncates to zero", standInSetBits)
	}
	if one<<past != 0 {
		t.Fatalf("standInSet is wider than standInSetBits (%d): the compile-time member check bounds the wrong number", standInSetBits)
	}
	if standInValueCount > standInSetBits {
		t.Fatalf("standInValueCount %d exceeds standInSetBits %d", standInValueCount, standInSetBits)
	}
	// Every declared member owns a distinct, in-range bit.
	seen := map[standInSet]bool{}
	for value := standInEmptyString; value <= standInEmptyCollection; value++ {
		bit := standInSetOf(value)
		if bit == 0 || seen[bit] {
			t.Fatalf("standInValue %d has no distinct bit in standInSet", value)
		}
		seen[bit] = true
	}
	if len(seen) != standInValueCount {
		t.Fatalf("bits %d, declared members %d", len(seen), standInValueCount)
	}
}

// TestStandInRefusesBeyondItsDeclaredBounds is patch 6's guard: both
// limits were asserted by nothing, so deleting either check left the
// package green. engine.worker.ts decodes a non-render byte response
// with NO transport bound, so these two are the only bound there is.
func TestStandInRefusesBeyondItsDeclaredBounds(t *testing.T) {
	t.Run("path count", func(t *testing.T) {
		var builder strings.Builder
		for index := 0; index <= designer.MaxStandInDataPaths; index++ {
			fmt.Fprintf(&builder, "{{p%d}} ", index)
		}
		_, err := standInData(standInTemplate(t, standInTextElement("e1", builder.String())))
		if err == nil {
			t.Fatalf("StandInData accepted more than %d paths", designer.MaxStandInDataPaths)
		}
		if !strings.Contains(err.Error(), fmt.Sprintf("more than %d data paths", designer.MaxStandInDataPaths)) {
			t.Fatalf("the refusal does not name the path limit: %v", err)
		}
	})

	t.Run("document bytes", func(t *testing.T) {
		// Few enough paths to clear the path limit, long enough names to
		// break the byte limit.
		const names = 450
		const width = 600
		var builder strings.Builder
		for index := 0; index < names; index++ {
			fmt.Fprintf(&builder, "{{%s%d}} ", strings.Repeat("a", width), index)
		}
		if names > designer.MaxStandInDataPaths {
			t.Fatalf("presence precondition: %d paths would trip the path limit first", names)
		}
		_, err := standInData(standInTemplate(t, standInTextElement("e1", builder.String())))
		if err == nil {
			t.Fatalf("StandInData accepted a document beyond %d bytes", designer.MaxStandInDataBytes)
		}
		if !strings.Contains(err.Error(), fmt.Sprintf("exceeds the %d-byte limit", designer.MaxStandInDataBytes)) {
			t.Fatalf("the refusal does not name the byte limit: %v", err)
		}
	})
}

