// standInSourceWithoutComments returns path's source with every comment
// removed, by PARSING it: parser.ParseFile without ParseComments drops
// comments entirely, and printer.Fprint renders what is left. A "//"
// search cannot do this correctly in either direction (see the test
// below), and this is a determinism guard, so it parses.
func standInSourceWithoutComments(t *testing.T, path string) string {
	t.Helper()
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
	var out bytes.Buffer
	if err := printer.Fprint(&out, token.NewFileSet(), file); err != nil {
		t.Fatalf("print %s: %v", path, err)
	}
	return out.String()
}

// stripLineComments is the NAIVE stripper this file used to rely on. It
// is kept for exactly one purpose: to be the contrast arm below, so the
// hardening is demonstrated against the thing it replaced rather than
// asserted. Nothing else calls it.
func stripLineComments(source string) string {
	lines := strings.Split(source, "\n")
	for index, line := range lines {
		if at := strings.Index(line, "//"); at >= 0 {
			lines[index] = line[:at]
		}
	}
	return strings.Join(lines, "\n")
}

// TestStandInCommentStrippingIsAParseNotASearch proves the hardening
// with the two cases the naive stripper got wrong, in OPPOSITE
// directions:
//
//   - a /* */ block comment: the search leaves it, so a clock named only
//     in block-comment prose would RED the no-clock scan falsely, and
//     worse, prose can hide code from the scan the other way round;
//   - a "//" inside a STRING LITERAL: the search truncates the line
//     there, so any real code after it — including a clock call —
//     BECOMES INVISIBLE to the scan. That is the direction that matters:
//     it is how a determinism guard silently stops guarding.
func TestStandInCommentStrippingIsAParseNotASearch(t *testing.T) {
	synthetic := "package probe\n\n/* a block comment naming time.Now */\nfunc probe() string {\n\tmarker := \"a // b\" + \"tail\"\n\treturn marker\n}\n"
	path := filepath.Join(t.TempDir(), "probe.go")
	if err := os.WriteFile(path, []byte(synthetic), 0o600); err != nil {
		t.Fatalf("write probe: %v", err)
	}
	naive := stripLineComments(synthetic)
	parsed := standInSourceWithoutComments(t, path)

	if !strings.Contains(naive, "time.Now") {
		t.Fatal("contrast arm broken: the naive stripper was supposed to leave the block comment behind")
	}
	if strings.Contains(parsed, "time.Now") {
		t.Fatal("the parse-based stripper left a block comment's contents in the scanned source")
	}
	if strings.Contains(naive, `"tail"`) {
		t.Fatal("contrast arm broken: the naive stripper was supposed to truncate at the \"//\" inside the string literal")
	}
	if !strings.Contains(parsed, `"tail"`) {
		t.Fatal("the parse-based stripper dropped code following a \"//\" inside a string literal — the scan would not see a clock there")
	}
}

